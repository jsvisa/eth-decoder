#!/usr/bin/env node
/**
 * Regenerates the coverage block in README.md from coverage/coverage-summary.json.
 *
 * Run after a coverage run:
 *   npm run test:coverage && npm run coverage:readme
 * or use the combined script:
 *   npm run test:coverage:readme
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const summaryPath = join(root, "coverage", "coverage-summary.json");
const readmePath = join(root, "README.md");

if (!existsSync(summaryPath)) {
  console.error(
    `✗ ${summaryPath} not found. Run \`npm run test:coverage\` first.`,
  );
  process.exit(1);
}

const { total } = JSON.parse(readFileSync(summaryPath, "utf-8"));
if (!total) {
  console.error("✗ No totals in coverage summary.");
  process.exit(1);
}

const block = [
  "<!-- COVERAGE:START (auto-generated by scripts/update-coverage-readme.js — do not edit between the markers) -->",
  "| Statements | Branches | Functions | Lines |",
  "| ---------- | -------- | --------- | ----- |",
  `| ${total.statements.pct}% | ${total.branches.pct}% | ${total.functions.pct}% | ${total.lines.pct}% |`,
  "",
  "_Regenerate with_ `npm run test:coverage:readme`.",
  "<!-- COVERAGE:END -->",
].join("\n");

let readme = readFileSync(readmePath, "utf-8");
const start = readme.indexOf("<!-- COVERAGE:START");
const end = readme.indexOf("<!-- COVERAGE:END -->");

if (start === -1 || end === -1) {
  console.error(
    "✗ README.md is missing the COVERAGE:START/COVERAGE:END markers.",
  );
  process.exit(1);
}

readme =
  readme.slice(0, start) +
  block +
  readme.slice(end + "<!-- COVERAGE:END -->".length);

writeFileSync(readmePath, readme);
console.log(
  `✓ README.md updated: statements ${total.statements.pct}%, branches ${total.branches.pct}%, functions ${total.functions.pct}%, lines ${total.lines.pct}%`,
);
